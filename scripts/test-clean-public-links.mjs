import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
import Links from '../site/run-links.js';
import Feed from '../site/feed-card.js';
import {runPath,shareOrigin} from '../server/share-routes.mjs';
import {html,linkPreviewCard,photoSlots} from '../server/public-run.mjs';

const run={id:'90a16040-8ad5-4096-978c-8b1f78f3dd2f',visibility:'public',title:'The project belongs on the run card.',caption:'Built galleries that put the product beside the person who made it, with real screenshots and a way into the full run.',profile_id:'11111111-1111-1111-1111-111111111111',profiles:{handle:'morkeeth',display_name:'Oscar Morkeeth'},commits:6,wall_time_s:7020,tool_calls:473};
const clean=runPath(run);
assert.equal(Links.runPath(run),clean);
assert.equal(Links.profilePath('MORKEETH'),'/morkeeth');
assert.equal(Links.runHref({...run,visibility:'private'}),'/?run='+run.id);
assert.equal(Links.runPath({...run,profiles:{handle:'api'}}),null);
const card=Feed.card(run),page=html(run);
assert.ok(card.includes(`href="${clean}`));
assert.doesNotMatch(card,/<a\b[^>]*href="[^"]*\?(?:run|u)=/);
assert.ok(page.includes(`rel="canonical" href="${shareOrigin}${clean}`));
assert.ok(page.includes(`property="og:image" content="${shareOrigin}/api/og?run=${run.id}&v=5"`),'share page points crawlers at the revised card');
assert.ok(page.includes(`href="/?legacy=1&run=${run.id}">Open in STRIVE`));
assert.doesNotMatch(page,/<script\b/i,'public share page stays script-free');
assert.ok(Feed.builderRow(run).includes(`href="${clean}"`));
assert.ok(Feed.builderRow(run).includes('href="/morkeeth"'));
const browser=new JSDOM('',{url:'https://striverun.app/',runScripts:'outside-only'}).window;
for(const name of ['run-links.js','run-contract.js','run-placeholders.js','run-estimates.js','run-context.js','run-story.js','feed-card.js','day.js','day-card.js','activity-order.js','activity-post.js'])browser.eval(readFileSync(new URL('../site/'+name,import.meta.url),'utf8'));
const signedOutFeed=new JSDOM(browser.StrivePost.render(run)).window.document;
const publicAnchors=[...signedOutFeed.querySelectorAll('a[href]')];
assert.ok(publicAnchors.length>=4,'the public card exposes title, media and secondary actions');
assert.ok(publicAnchors.some(a=>a.getAttribute('href')===clean));
assert.equal(publicAnchors.filter(a=>/[?&](?:run|u)=/.test(a.getAttribute('href'))).length,0,'signed-out public run anchors use clean paths throughout');
const app=readFileSync(new URL('../site/index.html',import.meta.url),'utf8');
assert.ok(app.indexOf('<script src="/run-links.js">')<app.indexOf('<script src="/activity-post.js">'),'link helpers load before feed cards');
const preview=linkPreviewCard(run);
const nodes=tree=>tree&&typeof tree==='object'?[tree,...[tree.props?.children].flat().flatMap(nodes)]:[];
const texts=tree=>nodes(tree).flatMap(node=>[node.props?.children].flat().filter(child=>typeof child==='string'));
assert.equal(preview.props.style.background,'#0047ff','the card sits on the brand blue');
assert.ok(nodes(preview).some(node=>node.props?.style?.background==='#0047ff'&&texts(node).some(text=>text.startsWith('Built galleries'))),'a run without a selected image or trace gets the blue caption tile');
assert.ok(!JSON.stringify(preview).includes('473'),'a tool-call total is not a fact on the link image (PRODUCT.md)');
assert.deepEqual(texts(preview).filter(text=>['6','1h 57m','Commits','Elapsed'].includes(text)),['6','Commits','1h 57m','Elapsed'],'recorded facts print figure then label, in PRODUCT.md order');
const shot='data:image/jpeg;base64,/9j/',avatar='data:image/png;base64,iVBORw0K';
const photoPreview=linkPreviewCard(run,{photoUrls:Array(3).fill(shot),avatar});
const tiles=nodes(photoPreview).filter(node=>node.type==='img'&&node.props.src===shot);
assert.equal(tiles.length,3,'three selected images reach the visual preview');
assert.deepEqual(tiles.map(({props})=>[props.width,props.height]),photoSlots(run,'link',3).map(slot=>[slot.width,slot.height]),'each image fills the slot the hosted route crops it to');
assert.equal(nodes(photoPreview).filter(node=>node.type==='img'&&node.props.src===avatar).length,1,'the avatar is drawn once');
console.log('PASS: public feed, profile, share page and preview use clean readable links; private URL stays private');
