import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
const source=readFileSync(new URL('../site/index.html',import.meta.url),'utf8');
const dom=new JSDOM('<article class="dc" id="one" data-count="2" data-at="0"><footer class="fc-foot"></footer><section class="dc-comments" hidden></section></article><b data-count="12">0</b>');
const {document}=dom.window;
dom.window.matchMedia=()=>({matches:true});
const countUp=source.slice(source.indexOf('function countUp(){'),source.indexOf('// a whole number gets'));
new Function('document','window',countUp+';countUp();')(document,dom.window);
assert.ok(document.querySelector('.dc .fc-foot'),'numeric animation must not replace a carousel');
assert.equal(document.querySelector('b').textContent,'12');
const binder=source.slice(source.indexOf('function bindCompactCard('),source.indexOf('async function feedCards('));
let change;const requests=[];
const bind=new Function('document','StriveDayCard','GrinderFeed','ME','social','wireKudos',binder+';return bindCompactCard;')(document,{wire:(_card,options)=>{change=options.onChange;return{}}},{actions:()=>'<a data-comment href="#">Comments</a>'},null,{thread:async(id,node)=>{requests.push({id,node})}},()=>{});
const card=document.querySelector('.dc'),deck={slides:[{key:'alpha',name:'Alpha',open:{id:'run-a',profile_id:'owner'}},{key:'beta',name:'Beta',open:{id:'run-b',profile_id:'owner'}}]};
bind(card,deck,{counts:{},mine:new Set()});
card.querySelector('[data-comment]').click();
assert.equal(requests[0].id,'run-a');
card.dataset.at='1';change(1);
assert.equal(card.dataset.runId,'run-b');
assert.equal(card.querySelector('.dc-comments').dataset.runId,'run-b');
assert.equal(card.querySelector('.dc-comments').hidden,true);
requests[0].node.textContent='delayed comment for Alpha';
assert.ok(!card.textContent.includes('delayed comment'),'late replies cannot leak into the next project');
card.querySelector('[data-comment]').click();
assert.equal(requests[1].id,'run-b');
assert.equal(card.querySelector('[data-comment]').getAttribute('aria-expanded'),'true');
console.log('PASS: carousel survives numeric animation; comments stay bound to selected run, including delayed replies');
